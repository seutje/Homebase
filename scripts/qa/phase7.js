async (page) => {
  const directory=await page.evaluate(()=>window.__TAURI_INTERNALS__.invoke('get_data_directory'));
  if(!directory.replaceAll('\\','/').includes('/.qa/v2-data')) throw new Error('Use isolated v2 QA data');
  await page.getByRole('button',{name:'+ Add task',exact:true}).click();
  await page.getByLabel('Task name').fill('V2 sheets');
  await page.getByLabel('Last completed').fill('2026-10-21');
  await page.getByRole('button',{name:'Save task',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const row=page.locator('.task-row').filter({has:page.getByText('V2 sheets',{exact:true})});
  await row.getByRole('button',{name:'Snooze',exact:true}).click();
  await page.getByLabel('Snooze until').fill('2026-11-03');
  await page.getByRole('button',{name:'Snooze task',exact:true}).click();
  await row.getByText(/^9 days ago \(\d+\s.+\)$/).waitFor();
  await row.getByText(/Snoozed until/).waitFor();
  await page.getByRole('button',{name:'0 Needs attention',exact:true}).waitFor();
  await page.getByRole('button',{name:'Snoozed · 1',exact:true}).click();
  await row.getByRole('button',{name:'Done',exact:true}).click();
  await row.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await row.getByText(/Snoozed until/).waitFor();
  await row.getByRole('button',{name:'Snooze',exact:true}).click();
  await page.getByRole('button',{name:'Unsnooze',exact:true}).click();
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('button',{name:'⚙ Settings'}).click();
  await page.getByLabel('Overdue grace (days)').fill('3');
  await page.getByRole('button',{name:'Save urgency defaults',exact:true}).click();
  await page.getByText('Urgency defaults saved.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await row.getByText(/Due within grace/).waitFor();
  await page.reload(); await row.getByText(/Due within grace/).waitFor();
  await row.getByRole('button').first().click();
  await page.getByRole('button',{name:'Edit task',exact:true}).click();
  await page.getByText('Personal urgency',{exact:true}).click();
  await page.getByLabel('Overdue grace (days)').fill('0');
  await page.getByRole('button',{name:'Save task',exact:true}).click();
  await page.getByRole('button',{name:'Close details'}).click();
  await row.getByText('2 days overdue',{exact:true}).waitFor();
  await page.screenshot({path:'.qa/phase7.png'});
  return 'Phase 7 passed: snooze filter, unchanged history, completion/undo, unsnooze, persisted defaults and task override';
}
